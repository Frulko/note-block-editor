export type IconName = keyof typeof PATHS | (string & {});

export interface IconOptions {
  /** Rendered size in px (default 16). */
  size?: number;
  /** Stroke width on the 24-grid (default 2). */
  stroke?: number;
  className?: string;
}

/** Build an inline SVG icon element. Unknown names render nothing visible. */
export function icon(name: IconName, options: IconOptions = {}): SVGElement {
  const { size = 16, stroke = 2, className } = options;
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', String(stroke));
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.classList.add('nbe-icon');
  if (className) svg.classList.add(...className.split(' '));
  svg.innerHTML = PATHS[name] ?? '';
  return svg;
}

